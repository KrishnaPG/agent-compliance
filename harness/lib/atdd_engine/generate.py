"""Rows + catalog + keyword library -> generated pytest files, manifest and a list of rows not generated.

Pure function of its inputs: the same inputs give identical bytes. `check` compares the files on disk with
what would be generated and reports stale, missing and hand-added files.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

import yaml

from .runtime import load_library
from .teaching import teach

REF = "docs/spec/packet-standards.md L3"
HEADER = "# Generated by atdd_engine from the criteria rows. Do not edit: regenerate with `python -m atdd_engine generate`.\n"


class Refusal(Exception):
    """The generator refuses its inputs; the message has the teaching shape."""


def load_rows(criteria_dir: Path) -> list[dict]:
    rows = []
    for f in sorted(Path(criteria_dir).glob("*.yaml")):
        doc = yaml.safe_load(f.read_text())
        for r in doc["criteria"]:
            r = dict(r)
            r["_slice"] = str(doc["slice"])
            rows.append(r)
    ids = [r["id"] for r in rows]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        raise Refusal(teach("ATDD-ROWS", f"row id {dup[0]} is used twice", "give each row one unique id", REF))
    return rows


def test_name(row_id: str) -> str:
    return "test_" + re.sub(r"[^0-9A-Za-z]", "_", row_id)


def _steps(row: dict):
    for g in row.get("given", []):
        for k, v in g.items():
            yield "given", k, v or {}
    for k, v in row["when"].items():
        yield "when", k, v or {}
    for t in row.get("then", []):
        for k, v in t.items():
            yield "then", k, v or {}


def not_generated_reason(row: dict, catalog: dict, library) -> str | None:
    """None when the row can be generated; else the reason (a catalog gap or an ambiguous key)."""
    ambiguous = getattr(library, "AMBIGUOUS", None)
    for kind, key, params in _steps(row):
        if key == "needs_keyword":
            return "needs_keyword: " + str(params.get("reason", ""))
        if key not in catalog[kind]:
            raise Refusal(teach("ATDD-KEY", f"row {row['id']} uses {kind} key {key}, which is not in the catalog", f"add {key} to docs/atdd/catalog.yaml or fix the row", REF))
        if ambiguous:
            why = ambiguous(kind, key, params)
            if why:
                return f"ambiguous {kind}.{key}: {why}"
    return None


def render_test(row: dict) -> str:
    out = [f"@pytest.mark.criterion({row['id']!r})", f"def {test_name(row['id'])}(ctx):"]
    out.append("    # " + " ".join(str(row.get("scenario", "")).split()))
    for kind, key, params in _steps(row):
        out.append(f"    ctx.{kind}({key!r}, {params!r})")
    return "\n".join(out) + "\n"


def render_conftest(rel_engine: str, rel_library: str, rel_fixtures: str) -> str:
    return (
        HEADER
        + "import sys\nfrom pathlib import Path\n\nimport pytest\n\n"
        + "_HERE = Path(__file__).resolve().parent\n"
        + f"sys.path.insert(0, str((_HERE / {rel_engine!r}).resolve()))\n"
        + "from atdd_engine.plugin import make_ctx, pytest_addoption, pytest_configure, pytest_runtest_makereport  # noqa: E402,F401\n\n"
        + f"LIBRARY = (_HERE / {rel_library!r}).resolve()\nFIXTURES = (_HERE / {rel_fixtures!r}).resolve()\n\n\n"
        + "@pytest.fixture\ndef ctx(request, tmp_path, record_property):\n"
        + "    yield from make_ctx(request, tmp_path, record_property, LIBRARY, FIXTURES)\n"
    )


def _j(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def generate(catalog_path, criteria_dir, library_dir, fixtures_dir, out_dir) -> dict[str, str]:
    """Return {file name: text} for the out dir."""
    catalog = yaml.safe_load(Path(catalog_path).read_text())
    library = load_library(Path(library_dir))
    rows = load_rows(Path(criteria_dir))
    out_dir = Path(out_dir).resolve()
    rel = lambda p: os.path.relpath(Path(p).resolve(), out_dir)  # noqa: E731
    engine_dir = Path(__file__).resolve().parent.parent
    files: dict[str, str] = {"conftest.py": render_conftest(rel(engine_dir), rel(library_dir), rel(fixtures_dir))}
    manifest: dict[str, dict] = {}
    skipped: dict[str, dict] = {}
    by_slice: dict[str, list[str]] = {}
    for r in rows:
        why = not_generated_reason(r, catalog, library)
        if why:
            skipped[r["id"]] = {"reason": why, "slice": r["_slice"]}
            continue
        fname = f"test_{r['_slice']}.py"
        by_slice.setdefault(fname, []).append(render_test(r))
        manifest[r["id"]] = {"node": f"{fname}::{test_name(r['id'])}", "slice": r["_slice"]}
    for fname, tests in sorted(by_slice.items()):
        files[fname] = HEADER + "import pytest\n\n\n" + "\n\n".join(tests)
    nodes = [m["node"] for m in manifest.values()]
    if len(nodes) != len(set(nodes)):
        raise Refusal(teach("ATDD-NODE", "two rows map to one test node", "give the rows ids that differ beyond case and punctuation", REF))
    files["manifest.json"] = _j({"criteria": manifest, "version": 1})
    files["not_generated.json"] = _j(skipped)
    return files


GENERATED_PATTERNS = ("test_*.py", "conftest.py", "manifest.json", "not_generated.json")


def write(files: dict[str, str], out_dir) -> None:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_bytes(text.encode())


def check(files: dict[str, str], out_dir) -> list[str]:
    """Teaching-shaped reports of stale, missing or hand-added generated files; empty when identical."""
    out_dir = Path(out_dir)
    report = []
    for name, text in sorted(files.items()):
        p = out_dir / name
        if not p.exists():
            report.append(teach("ATDD-MISSING", f"{name} is not generated yet", "run `python -m atdd_engine generate`", REF))
        elif p.read_bytes() != text.encode():
            report.append(teach("ATDD-STALE", f"{name} differs from its rows (stale or hand-edited)", "regenerate with `python -m atdd_engine generate`; never edit it", REF))
    if out_dir.is_dir():
        for pat in GENERATED_PATTERNS:
            for p in sorted(out_dir.glob(pat)):
                if p.name not in files:
                    report.append(teach("ATDD-EXTRA", f"{p.name} is in the generated dir but no row produces it", "delete it; tests come only from rows", REF))
    return report
